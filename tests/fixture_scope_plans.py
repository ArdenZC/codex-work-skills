def scope_plan_for(task: str, artifact: str) -> ScopePlan:
    plan = next((p for p in SCOPE_PLANS if p.task == task), None)
    if plan is not None:
        if artifact != plan.artifact:
            raise ValueError('scope fixture output conflicts with its task plan')
        return plan
    # Structural test briefs may supply arbitrary tasks. The fallback teaches
    # only that supplied task/output relation; it never injects a specific topic.
    return ScopePlan(task, artifact,
        f'说明“{task}”的工作范围，列出任务已经给定的对象与要求。',
        f'按照“{task}”核对{artifact}，逐项说明成果如何回应本课任务。',
        f'“{task}”的任务要求必须与{artifact}中的成果对应，说明要能指向实际产出。',
        f'将“{task}”的要求落实到{artifact}，区分已完成的任务内容与尚未完成的要求。')
